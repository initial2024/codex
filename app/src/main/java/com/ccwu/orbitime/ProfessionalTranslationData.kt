    private fun punctuateChinese(text: String): String {
        return when {
            text.endsWith("？") || text.endsWith("！") || text.endsWith("。") -> text
            text.contains("什么") || text.contains("谁") || text.contains("是否") || text.contains("吗") -> "$text？"
            else -> "$text。"
        }
    }
