    private fun punctuateChinese(text: String): String {
        if (text.endsWith("？") || text.endsWith("。") || text.endsWith("！")) return text
        return if (text.contains("什么") || text.contains("谁") || text.contains("怎么办") || text.contains("为什么")) "$text？" else "$text。"
    }
